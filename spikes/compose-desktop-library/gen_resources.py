"""Generates a desktop stand-in for Android's R class from upstream's real resources.

Reads app/src/main/res/values/strings*.xml (strings, plurals) and app/src/main/res/drawable/ and writes:
  src/generated/kotlin/com/nendo/argosy/R.kt          R.string / R.plurals / R.drawable ids
  src/generated/resources/spike/resources.tsv         id -> English text, read by the stringResource shim

usage: python3 -I gen_resources.py
"""
import os
import re
import xml.etree.ElementTree as ET

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, "..", "..", "app", "src", "main", "res")
OUT_KT = os.path.join(HERE, "src", "generated", "kotlin", "com", "nendo", "argosy", "R.kt")
OUT_TSV = os.path.join(HERE, "src", "generated", "resources", "spike", "resources.tsv")


def android_text(el):
    """Android resource text: inner markup flattened, quotes and backslash escapes resolved."""
    raw = "".join(el.itertext())
    out, quoted, i = [], False, 0
    while i < len(raw):
        c = raw[i]
        if c == "\\" and i + 1 < len(raw):
            n = raw[i + 1]
            out.append({"n": "\n", "t": "\t"}.get(n, n))
            i += 2
            continue
        if c == '"':
            quoted = not quoted
        elif not quoted and c in " \n\t":
            if not out or out[-1] != " ":
                out.append(" ")
        else:
            out.append(c)
        i += 1
    return "".join(out).strip()


def esc(s):
    return s.replace("\\", "\\\\").replace("\t", "\\t").replace("\n", "\\n")


def main():
    strings, plurals = {}, {}
    values = os.path.join(RES, "values")
    for f in sorted(os.listdir(values)):
        if not (f.startswith("strings") and f.endswith(".xml")):
            continue
        root = ET.parse(os.path.join(values, f)).getroot()
        for el in root:
            name = el.get("name")
            if el.tag == "string":
                strings[name] = android_text(el)
            elif el.tag == "plurals":
                plurals[name] = {item.get("quantity"): android_text(item) for item in el}
    drawables = sorted({os.path.splitext(f)[0] for f in os.listdir(os.path.join(RES, "drawable"))})

    rows, kinds = [], {"string": [], "plurals": [], "drawable": []}
    next_id = 0x7F000000
    for name in sorted(strings):
        kinds["string"].append((name, next_id)); rows.append(f"{next_id}\tstring\t{name}\t{esc(strings[name])}"); next_id += 1
    for name in sorted(plurals):
        enc = "\u001f".join(f"{q}={esc(v)}" for q, v in plurals[name].items())
        kinds["plurals"].append((name, next_id)); rows.append(f"{next_id}\tplurals\t{name}\t{enc}"); next_id += 1
    for name in drawables:
        kinds["drawable"].append((name, next_id)); rows.append(f"{next_id}\tdrawable\t{name}\t{name}"); next_id += 1

    os.makedirs(os.path.dirname(OUT_KT), exist_ok=True)
    os.makedirs(os.path.dirname(OUT_TSV), exist_ok=True)
    with open(OUT_TSV, "w", encoding="utf-8") as fh:
        fh.write("\n".join(rows) + "\n")
    with open(OUT_KT, "w", encoding="utf-8") as fh:
        fh.write("// Generated by gen_resources.py from app/src/main/res. Do not edit.\n")
        fh.write("@file:Suppress(\"ClassName\", \"ObjectPropertyName\")\n\npackage com.nendo.argosy\n\nobject R {\n")
        for kind, entries in kinds.items():
            fh.write(f"    object {kind} {{\n")
            for name, rid in entries:
                fh.write(f"        const val {name}: Int = {rid}\n")
            fh.write("    }\n")
        fh.write("}\n")
    print(f"R: {len(strings)} strings, {len(plurals)} plurals, {len(drawables)} drawables")


main()
